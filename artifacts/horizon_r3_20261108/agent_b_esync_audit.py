#!/usr/bin/env python3
"""Read-only audit of saved target DT + pinned public ESYNC sources; no device IO."""
import argparse
import json
import tarfile
import urllib.request
from pathlib import Path

DRIVER_COMMIT = 'fa008c43c070ff20faa33853649f5dfd4c427e99'
DT_COMMIT = 'f088523dfba85c95c15f43726fcf972c0c7a957a'
# Ranges retain original source line numbers; source snippets remain GPL/BSD as upstream.
RANGES = {
 'msm/msm_drv.h': [(996,1008)],
 'msm/dsi/dsi_panel.c': [(578,593),(916,933),(2447,2527),(3439,3448),(3453,3463)],
 'msm/dsi/dsi_display.c': [(9191,9198),(9253,9260),(9275,9297),(9376,9395)],
 'msm/sde/sde_connector.c': [(1526,1538),(4244,4264)],
 'msm/sde/sde_encoder_phys_vid.c': [(861,884),(890,939)],
 'msm/sde/sde_hw_intf.c': [(127,151),(340,388),(390,412),(985,994),(1553,1565)],
 'bindings/mdss-dsi-panel.yaml': [(671,700),(737,741),(816,820)],
 'display/canoe-sde-display-pinctrl-common.dtsi': [(141,179)],
 'display/canoe-sde-display.dtsi': [(120,133),(360,393)],
 'display/canoe-sde-display-common.dtsi': [(480,518)],
}

def main():
 p=argparse.ArgumentParser()
 p.add_argument('--cache',type=Path,required=True)
 p.add_argument('--archive',type=Path,required=True)
 p.add_argument('--fetch',action='store_true',help='fetch pinned public sources into cache; never connects to target')
 p.add_argument('--repo',type=Path,default=Path(__file__).resolve().parents[2])
 p.add_argument('--output',type=Path,default=Path(__file__).resolve().parent)
 a=p.parse_args()
 if a.fetch:
  a.cache.mkdir(parents=True,exist_ok=True)
  if not a.archive.exists():
   url=f'https://codeload.github.com/MotorolaMobilityLLC/kernel-display-devicetree/tar.gz/{DT_COMMIT}'
   a.archive.write_bytes(urllib.request.urlopen(url,timeout=30).read())
  with tarfile.open(a.archive,'r:gz') as tar:
   for member in tar.getmembers():
    if not member.isfile(): continue
    name=member.name.split('/',1)[1]
    if name in RANGES:
     (a.cache/name.replace('/','__')).write_bytes(tar.extractfile(member).read())
  for name in RANGES:
   if not name.startswith('msm/'): continue
   dest=a.cache/name.replace('/','__')
   if not dest.exists():
    url=f'https://raw.githubusercontent.com/MotorolaMobilityLLC/kernel-msm-5.4-techpack-display/{DRIVER_COMMIT}/{name}'
    dest.write_bytes(urllib.request.urlopen(url,timeout=30).read())
 target=a.repo/'artifacts/device_tree/selected_boe_v4'
 files=sorted(x for x in target.rglob('*') if x.is_file())
 gates=['qcom,mdss-esync','qcom,mdss-esync-emsync-fps',
        'qcom,mdss-dsi-panel-esync-emsync-switch-enabled',
        'qcom,mdss-dsi-esync-post-on-commands','qcom,mdss-dsi-em-pulse-switch-command']
 selected={k:[str(x.relative_to(target)) for x in files if x.name==k] for k in gates}
 panel_type=(target/'qcom,mdss-dsi-panel-type').read_bytes().rstrip(b'\x00').decode()
 esync_hits=[]; ili_files=[]; member_count=0
 with tarfile.open(a.archive,'r:gz') as tar:
  for m in tar.getmembers():
   if not m.isfile(): continue
   member_count+=1
   name=m.name.split('/',1)[1]
   s=tar.extractfile(m).read().decode('utf-8','replace')
   lines=[{'line':i,'text':l.strip()} for i,l in enumerate(s.splitlines(),1) if 'esync' in l.lower()]
   if lines: esync_hits.append({'path':name,'matches':lines})
   if 'ili97701' in name.lower():
    ili_files.append({'path':name,'esync_matches':lines})
   if name in RANGES:
    cache=a.cache/name.replace('/','__')
    if cache.read_text()!=s: raise ValueError('cached DT content differs from pinned archive: '+name)
 excerpts=['# Agent B: pinned primary source excerpts', '',
           'Generated by agent_b_esync_audit.py. Prefix L is the ORIGINAL source line; trailing whitespace is normalized. '+
           'No target compatibility is implied by a reference implementation.','']
 for name,ranges in RANGES.items():
  is_driver=name.startswith('msm/')
  repo='kernel-msm-5.4-techpack-display' if is_driver else 'kernel-display-devicetree'
  commit=DRIVER_COMMIT if is_driver else DT_COMMIT
  s=(a.cache/name.replace('/','__')).read_text().splitlines()
  for start,end in ranges:
   url=f'https://github.com/MotorolaMobilityLLC/{repo}/blob/{commit}/{name}#L{start}-L{end}'
   excerpts.extend([f'## {name}:{start}–{end}', '',f'Source: {url}', '', '```text'])
   excerpts.extend(f'L{i}: {s[i-1]}'.rstrip() for i in range(start,end+1))
   excerpts.extend(['```',''])
 (a.output/'agent_b_esync_primary_excerpts.md').write_text('\n'.join(excerpts).rstrip()+'\n')
 result={'scope':'offline saved target DT + one pinned official public source corpus',
         'target_saved_property_count':len(files),'target_panel_type':panel_type,
         'target_gate_paths':selected,
         'source_dt_commit':DT_COMMIT,'source_driver_commit':DRIVER_COMMIT,
         'source_archive_file_count':member_count,'exact_ili97701_files':ili_files,
         'source_esync_matches':esync_hits,
         'claim_limit':'No target board connectivity, DDIC external-sync capability or physical PWM measurement established.'}
 (a.output/'agent_b_esync_audit.json').write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n')
 print(json.dumps({k:v for k,v in result.items() if k not in ['source_esync_matches']},indent=2))
 print('ESYNC source files:',len(esync_hits))

if __name__=='__main__': main()
