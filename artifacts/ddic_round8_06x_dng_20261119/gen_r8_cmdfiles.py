#!/usr/bin/env python3
"""Generate Round 8 per-phase DDIC cmdfiles for r8_ddic.sh (host-side helper).

Values come from the stock cmd_v4 dc-on/dc-off tables in
artifacts/cn_panel_commands.json (panel 8) cross-checked against live
Round 7 readbacks at DBV 2048 (51/52 matched exactly).
Outputs plain-text cmdfiles into the given directory; prints the file list.
"""
import sys
from pathlib import Path

A2_ON = ('0xA2 ' + ' '.join(['0x10 0x10 0x10 0x10 0x48 0x10 0x10 0x74 0x7b 0xb4'] * 3)).split()
# Note: dc-off restoration is snapshot-based (make_r8_ret.py), and the addressed
# control phases (r8_ctl_80off/r8_ctl_80on) were generated ad-hoc in-session,
# not by this generator; this file covers the 8 planned phases only.
# 63:F2/F3 (bank 53:F0=01): dc-on moves five 0x20 bytes from F3 to F2.
F2_ON = ['0xF2', '0x00', '0x00', '0x00', '0x00', '0x00', '0x20', '0x20', '0x20', '0x20', '0x20',
         '0x00', '0x00', '0x00', '0x00', '0x00', '0x00']
F3_ON = ['0xF3'] + ['0x00'] * 16
# PAM block: (page, reg+3 data bytes) dc-on and dc-off values, stock cmd_v4 table.
PAM_ON = [
    ('5A', '0x86 0x0a 0x1e 0x01'), ('5A', '0x8a 0x32 0x38 0x18'), ('5A', '0x8f 0x6e 0x6c 0x32'),
    ('5A', '0x90 0x14 0x43 0x01'), ('5A', '0x91 0x13 0x40 0x00'), ('5A', '0x92 0x11 0x3f 0x00'),
    ('5A', '0x93 0x0e 0x3c 0x00'), ('5A', '0x94 0x06 0x1a 0x00'), ('5A', '0x95 0x46 0x46 0x37'),
    ('5A', '0x9b 0x01 0x00 0x00'), ('5A', '0x9c 0x48 0x42 0x3c'), ('5A', '0xae 0x15 0x2d 0x07'),
    ('5A', '0xb3 0x36 0x3d 0x22'), ('5A', '0xb9 0x36 0x3d 0x30'), ('5A', '0xbf 0x00 0xf8 0xfe'),
    ('5A', '0xc0 0x44 0x46 0x3e'), ('5A', '0xd7 0x24 0x34 0x22'), ('5A', '0xdd 0x34 0x43 0x38'),
    ('5A', '0xe4 0x3c 0x43 0x3d'),
    ('5B', '0xdd 0x40 0x44 0x47'),
    ('5C', '0xc8 0x14 0x19 0x06'), ('5C', '0xc9 0x14 0x19 0x06'), ('5C', '0xca 0x00 0x14 0x00'),
]
PAM_OFF = [
    ('5A', '0x86 0x0a 0x1e 0x04'), ('5A', '0x8a 0x12 0x2e 0x0f'), ('5A', '0x8f 0x27 0x3e 0x23'),
    ('5A', '0x90 0x0a 0x09 0x01'), ('5A', '0x91 0x09 0x06 0x00'), ('5A', '0x92 0x07 0x05 0x00'),
    ('5A', '0x93 0x04 0x02 0x00'), ('5A', '0x94 0x00 0x00 0x00'), ('5A', '0x95 0x26 0x24 0x16'),
    ('5A', '0x9b 0x00 0x00 0x00'), ('5A', '0x9c 0x34 0x3e 0x3c'), ('5A', '0xae 0x10 0x2d 0x07'),
    ('5A', '0xb3 0x1c 0x21 0x22'), ('5A', '0xb9 0x24 0x1c 0x20'), ('5A', '0xbf 0x09 0x00 0x00'),
    ('5A', '0xc0 0x3a 0x39 0x3e'), ('5A', '0xd7 0x1a 0x20 0x1d'), ('5A', '0xdd 0x2a 0x27 0x33'),
    ('5A', '0xe4 0x32 0x30 0x3d'),
    ('5B', '0xdd 0x39 0x3a 0x42'),
    ('5C', '0xc8 0x08 0x04 0x06'), ('5C', '0xc9 0x08 0x04 0x06'), ('5C', '0xca 0x00 0x00 0x00'),
]

READS = [
    ('00', '2', '0x52'), ('23', '1', '0xA9'), ('23', '3', '0xC1'), ('23', '1', '0x80'),
    ('23', '1', '0x85'), ('24', '1', '0x9D'), ('51', '6', '0xA1'), ('51', '6', '0xA2'),
    ('52', '6', '0x81'), ('52', '6', '0x82'), ('53', '2', '0x95'), ('53', '30', '0xA2'),
]
# Bank-wrapped live snapshot of the F-bank masks (R3-proven read route).
F_SNAPSHOT = ['W 53 0xF0 0x01', 'R 63 16 0xF2', 'R 63 16 0xF3', 'W 53 0xF0 0x00']


def reads(pam=False):
    out = [f'R {p} {l} {r}' for p, l, r in READS]
    if pam:
        out += [f'R {p} {l} {r}' for p, l, r in
                [(p, '3', '0x' + d.split()[0].upper()[2:]) for p, d in PAM_ON]] + F_SNAPSHOT
    return out


# Full live snapshot (all 23 PAM registers + F-bank masks + standard set) opens the
# session; r8_ret restores THIS snapshot (host-generated), not assumed table values.
PHASES = {
    'r8_base': ['R ' + p + ' 3 0x' + d.split()[0].upper()[2:] for p, d in PAM_OFF]
    + F_SNAPSHOT + reads(pam=False),
    'r8_a9a2': ['W 23 0xA9 0x8e', 'W 53 ' + ' '.join(A2_ON)],
    'r8_add9d': ['W 24 0x9D 0x8e'],
    'r8_add80': ['W 23 0x80 0x90'],
    'r8_add95': ['W 53 0x95 0x44 0x50'],
    'r8_add5152': [
        'W 51 0xA1 0x44 0x44 0x79 0x79 0x22 0x22',
        'W 51 0xA2 0x78 0x78 0x78 0x78 0x22 0x22',
        'W 52 0x81 0x46 0x47 0x49 0x48 0x00 0x00',
        'W 52 0x82 0x4a 0x4a 0x4b 0x4b 0x00 0x00',
    ],
    'r8_addf23': [
        'W 53 0xF0 0x01', 'W 63 ' + ' '.join(F2_ON), 'W 63 ' + ' '.join(F3_ON),
        'W 53 0xF0 0x00',
    ],
    'r8_addpam': ['W ' + p + ' ' + d for p, d in PAM_ON],
}
# r8_ret is NOT table-driven: the host regenerates it from the live r8_base snapshot
# (see make_r8_ret.py), restoring exactly what was overwritten, in R3's footsteps
# where live F2/F3 did not equal the vendor dc-off table.


def main(outdir: str) -> int:
    base = Path(outdir)
    base.mkdir(parents=True, exist_ok=True)
    for name, writes in PHASES.items():
        pam = name in ('r8_addpam',)
        lines = writes + ([] if name == 'r8_base' else reads(pam=pam))
        (base / f'{name}.cmd').write_text('\n'.join(lines) + '\n')
        print(base / f'{name}.cmd', len(lines), 'lines')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else '.'))
