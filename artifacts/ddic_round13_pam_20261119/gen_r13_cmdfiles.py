#!/usr/bin/env python3
"""Generate Round 13 PAM-interpolation cmdfiles (host-side).

In the cumulative-landed DC state at readback DBV 460, the stock dc-on PAM
block is replaced by per-byte linear interpolations between dc-off and
dc-on values (25/50/75% points). Each probe file FIRST restores 53:95=44 50 (the last R12 probe left 55 28),
then writes the 23 interpolated PAM registers, then reads back.
"""
import sys
from pathlib import Path

PAM_OFF = [
    ('5A', '0x86', [0x0a, 0x1e, 0x04]), ('5A', '0x8a', [0x12, 0x2e, 0x0f]),
    ('5A', '0x8f', [0x27, 0x3e, 0x23]), ('5A', '0x90', [0x0a, 0x09, 0x01]),
    ('5A', '0x91', [0x09, 0x06, 0x00]), ('5A', '0x92', [0x07, 0x05, 0x00]),
    ('5A', '0x93', [0x04, 0x02, 0x00]), ('5A', '0x94', [0x00, 0x00, 0x00]),
    ('5A', '0x95', [0x26, 0x24, 0x16]), ('5A', '0x9b', [0x00, 0x00, 0x00]),
    ('5A', '0x9c', [0x34, 0x3e, 0x3c]), ('5A', '0xae', [0x10, 0x2d, 0x07]),
    ('5A', '0xb3', [0x1c, 0x21, 0x22]), ('5A', '0xb9', [0x24, 0x1c, 0x20]),
    ('5A', '0xbf', [0x09, 0x00, 0x00]), ('5A', '0xc0', [0x3a, 0x39, 0x3e]),
    ('5A', '0xd7', [0x1a, 0x20, 0x1d]), ('5A', '0xdd', [0x2a, 0x27, 0x33]),
    ('5A', '0xe4', [0x32, 0x30, 0x3d]),
    ('5B', '0xdd', [0x39, 0x3a, 0x42]),
    ('5C', '0xc8', [0x08, 0x04, 0x06]), ('5C', '0xc9', [0x08, 0x04, 0x06]),
    ('5C', '0xca', [0x00, 0x00, 0x00]),
]
PAM_ON = [
    ('5A', '0x86', [0x0a, 0x1e, 0x01]), ('5A', '0x8a', [0x32, 0x38, 0x18]),
    ('5A', '0x8f', [0x6e, 0x6c, 0x32]), ('5A', '0x90', [0x14, 0x43, 0x01]),
    ('5A', '0x91', [0x13, 0x40, 0x00]), ('5A', '0x92', [0x11, 0x3f, 0x00]),
    ('5A', '0x93', [0x0e, 0x3c, 0x00]), ('5A', '0x94', [0x06, 0x1a, 0x00]),
    ('5A', '0x95', [0x46, 0x46, 0x37]), ('5A', '0x9b', [0x01, 0x00, 0x00]),
    ('5A', '0x9c', [0x48, 0x42, 0x3c]), ('5A', '0xae', [0x15, 0x2d, 0x07]),
    ('5A', '0xb3', [0x36, 0x3d, 0x22]), ('5A', '0xb9', [0x36, 0x3d, 0x30]),
    ('5A', '0xbf', [0x00, 0xf8, 0xfe]), ('5A', '0xc0', [0x44, 0x46, 0x3e]),
    ('5A', '0xd7', [0x24, 0x34, 0x22]), ('5A', '0xdd', [0x34, 0x43, 0x38]),
    ('5A', '0xe4', [0x3c, 0x43, 0x3d]),
    ('5B', '0xdd', [0x40, 0x44, 0x47]),
    ('5C', '0xc8', [0x14, 0x19, 0x06]), ('5C', '0xc9', [0x14, 0x19, 0x06]),
    ('5C', '0xca', [0x00, 0x14, 0x00]),
]


def interp(frac: float):
    out = []
    for (p, r, off), (_, _, on) in zip(PAM_OFF, PAM_ON):
        val = [round(o + (n - o) * frac) for o, n in zip(off, on)]
        out.append((p, r, val))
    return out


def main(outdir: str) -> int:
    base = Path(outdir)
    base.mkdir(parents=True, exist_ok=True)
    reads = ['R 00 2 0x52', 'R 23 1 0xA9', 'R 23 3 0xC1',
             'R 5A 3 0x8A', 'R 5A 3 0xBF', 'R 5C 3 0xCA', 'R 53 2 0x95']
    for tag, frac in [('pam25', 0.25), ('pam50', 0.50), ('pam75', 0.75),
                      ('pam_on_ref', 1.0)]:
        lines = (['W 53 0x95 0x44 0x50']
                 + [f'W {p} {r} ' + ' '.join(f'0x{b:02x}' for b in v)
                    for p, r, v in interp(frac)] + reads)
        (base / f'r13_{tag}.r13').write_text('\n'.join(lines) + '\n')
        print(base / f'r13_{tag}.r13', len(lines), 'lines')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else '.'))
