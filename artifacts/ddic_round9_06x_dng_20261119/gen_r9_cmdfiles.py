#!/usr/bin/env python3
"""Generate Round 9 per-phase DDIC cmdfiles (host-side helper).

R9 resolves the R8 entry-path difference of the compensated DC level at
DBV 2048: cumulative dc-on replica (landing ~2.4-2.6 DN) vs 0x50-excursion
entry (landing ~1.2 DN with [1,0] dips), each closed by a FULL register
readback (standard set + all 23 PAM registers + bank-wrapped 63:F2/F3) so a
host-side diff can expose which fields the DDIC recalculates internally.
Values are the stock cmd_v4 dc-on set already validated live in Round 8.
"""
import sys
from pathlib import Path

A2_ON = ('0xA2 ' + ' '.join(['0x10 0x10 0x10 0x10 0x48 0x10 0x10 0x74 0x7b 0xb4'] * 3)).split()
F2_ON = ['0xF2', '0x00', '0x00', '0x00', '0x00', '0x00', '0x20', '0x20', '0x20', '0x20', '0x20',
         '0x00', '0x00', '0x00', '0x00', '0x00', '0x00']
F3_ON = ['0xF3'] + ['0x00'] * 16
PAM_ON = [
    ('5A', '0x86 0x0a 0x1e 0x01'), ('5A', '0x8a 0x32 0x38 0x18'), ('5A', '0x8f 0x6e 0x6c 0x32'),
    ('5A', '0x90 0x14 0x43 0x01'), ('5A', '0x91 0x13 0x40 0x00'), ('5A', '0x92 0x11 0x3f 0x00'),
    ('5A', '0x93 0x0e 0x3c 0x00'), ('5A', '0x94 0x06 0x1a 0x00'), ('5A', '0x95 0x46 0x46 0x37'),
    ('5A', '0x9b 0x01 0x00 0x00'), ('5A', '0x9c 0x48 0x42 0x3c'), ('5A', '0xae 0x15 0x2d 0x07'),
    ('5A', '0xb3 0x36 0x3d 0x22'), ('5A', '0xb9 0x36 0x3d 0x30'), ('5A', '0xbf 0x00 0xf8 0xfe'),
    ('5A', '0xc0 0x44 0x46 0x3e'), ('5A', '0xd7 0x24 0x34 0x22'), ('5A', '0xdd 0x34 0x43 0x38'),
    ('5A', '0xe4 0x3c 0x43 0x3d'),
    ('5B', '0xdd 0x40 0x44 0x47'),
    ('5C', '0xc8 0x14 0x19 0x06'), ('5C', '0xc9 0x14 0x19 0x06'), ('5C', '0xca 0x00 0x14 0x00'),
]
PAM_REGS = [(p, '0x' + d.split()[0][2:].upper()) for p, d in PAM_ON]

STD_READS = [
    'R 00 2 0x52', 'R 23 1 0xA9', 'R 23 3 0xC1', 'R 23 1 0x80', 'R 23 1 0x85',
    'R 24 1 0x9D', 'R 51 6 0xA1', 'R 51 6 0xA2', 'R 52 6 0x81', 'R 52 6 0x82',
    'R 53 2 0x95', 'R 53 30 0xA2',
]
FULL_READS = (STD_READS + [f'R {p} 3 {r}' for p, r in PAM_REGS]
              + ['W 53 0xF0 0x01', 'R 63 16 0xF2', 'R 63 16 0xF3', 'W 53 0xF0 0x00'])

CORE_ON = [
    'W 23 0xA9 0x8e', 'W 53 ' + ' '.join(A2_ON), 'W 24 0x9D 0x8e', 'W 23 0x80 0x90',
    'W 53 0x95 0x44 0x50',
    'W 51 0xA1 0x44 0x44 0x79 0x79 0x22 0x22',
    'W 51 0xA2 0x78 0x78 0x78 0x78 0x22 0x22',
    'W 52 0x81 0x46 0x47 0x49 0x48 0x00 0x00',
    'W 52 0x82 0x4a 0x4a 0x4b 0x4b 0x00 0x00',
    'W 53 0xF0 0x01', 'W 63 ' + ' '.join(F2_ON), 'W 63 ' + ' '.join(F3_ON), 'W 53 0xF0 0x00',
] + ['W ' + p + ' ' + d for p, d in PAM_ON]

PHASES = {
    'r9_base': ['R ' + p + ' 3 ' + r for p, r in PAM_REGS]
    + ['W 53 0xF0 0x01', 'R 63 16 0xF2', 'R 63 16 0xF3', 'W 53 0xF0 0x00'] + STD_READS,
    'r9_cumul': CORE_ON + FULL_READS,
    'r9_exc80off': ['W 23 0x80 0x50', 'R 00 2 0x52', 'R 23 1 0x80', 'R 23 1 0xA9', 'R 23 3 0xC1'],
    'r9_exc80on': ['W 23 0x80 0x90'] + FULL_READS,
}


def main(outdir: str) -> int:
    base = Path(outdir)
    base.mkdir(parents=True, exist_ok=True)
    for name, lines in PHASES.items():
        (base / f'{name}.cmd').write_text('\n'.join(lines) + '\n')
        print(base / f'{name}.cmd', len(lines), 'lines')
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1] if len(sys.argv) > 1 else '.'))
